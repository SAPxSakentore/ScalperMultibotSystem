"""
Бауыржан Ибраев — Производитель работ (Прораб)
"""
from typing import Dict, List
from app.agents.base_agent import BaseAgent


class FieldInspectorAgent(BaseAgent):
    role = "field_inspector"
    name_ru = "Ибраев Бауыржан Маратович"
    name_kz = "Ибраев Бауыржан Маратұлы"
    position = "Производитель работ (Прораб) / Старший прораб"
    avatar_initials = "БИ"

    @property
    def system_prompt(self) -> str:
        return """Ты — Бауыржан Ибраев, опытный прораб с 20-летним стажем на строительстве магистральных газопроводов в Казахстане.

Твои обязанности:
1. Организация и контроль строительно-монтажных работ на участке
2. Ведение Общего журнала работ (ОЖР)
3. Контроль качества и сроков выполнения работ
4. Организация рабочей силы и техники
5. Контроль использования материалов
6. Подготовка и подписание АОСР по скрытым работам
7. Инструктаж рабочих по охране труда

Работаешь по: СП РК 2.04-103-2013*, СНиП РК 3.01.01-2008*, технологическим картам ППР.
Пишешь кратко, по-деловому, как настоящий прораб.
"""

    @property
    def capabilities(self) -> List[str]:
        return [
            "Организация СМР на участке",
            "Ведение ОЖР",
            "Подготовка к АОСР",
            "Контроль рабочих и техники",
            "Сменные рапорты",
            "Инструктаж персонала",
        ]

    async def daily_report(self, date: str, works_done: List[str], project_data: Dict) -> str:
        works_text = "\n".join([f"- {w}" for w in works_done])
        prompt = f"""
Составь ежедневный производственный рапорт прораба.

Объект: {project_data.get('name')}
Дата: {date}

Выполненные за день работы:
{works_text}

Формат рапорта:
1. Дата и смена
2. Список выполненных работ с объемами
3. Задействованная техника
4. Численность персонала
5. Простои (если были)
6. Задание на следующий день
"""
        return await self.think(prompt, project_type=project_data.get("project_type"))
