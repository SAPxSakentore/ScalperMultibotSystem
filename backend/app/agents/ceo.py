"""
Айгерим Сатова — Генеральный директор
"""
from typing import Dict, List
from app.agents.base_agent import BaseAgent


class CEOAgent(BaseAgent):
    role = "ceo"
    name_ru = "Сатова Айгерим Болатовна"
    name_kz = "Сатова Айгерім Болатқызы"
    position = "Генеральный директор / Руководитель компании"
    avatar_initials = "АС"

    @property
    def system_prompt(self) -> str:
        return """Ты — Айгерим Сатова, Генеральный директор строительной компании KazBuildOS в Республике Казахстан с 20-летним опытом в отрасли.

Твои обязанности:
1. Стратегическое управление компанией и портфелем проектов
2. Принятие ключевых решений по проектам
3. Взаимодействие с инвесторами, государственными органами
4. Утверждение бюджетов и контрактов
5. Управление репутацией компании
6. Обеспечение соответствия деятельности законодательству РК

Отвечаешь на стратегические вопросы, принимаешь высокоуровневые решения.
Используй деловой, профессиональный стиль общения.
"""

    @property
    def capabilities(self) -> List[str]:
        return [
            "Стратегическое управление проектами",
            "Принятие ключевых решений",
            "Согласование бюджетов и контрактов",
            "Взаимодействие с госорганами",
            "Общий статус по портфелю проектов",
        ]

    async def get_portfolio_summary(self, projects: List[Dict]) -> str:
        projects_text = "\n".join([
            f"- {p.get('name')} ({p.get('status')}): {p.get('progress_percent', 0)}%"
            for p in projects
        ])
        prompt = f"""
Подготовь краткий статусный отчет по портфелю проектов для руководства.

Проекты:
{projects_text}

Составь краткий executive summary:
1. Общий статус портфеля
2. Ключевые достижения
3. Критические риски и проблемы
4. Рекомендации для принятия решений
"""
        return await self.think(prompt)
