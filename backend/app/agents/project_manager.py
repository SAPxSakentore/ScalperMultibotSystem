"""
Нурлан Бекенов — Руководитель проекта / ГИП
"""
from typing import Dict, Any, Optional, List
from app.agents.base_agent import BaseAgent


class ProjectManagerAgent(BaseAgent):
    role = "project_manager"
    name_ru = "Бекенов Нурлан Асылбекович"
    name_kz = "Бекенов Нұрлан Асылбекұлы"
    position = "Главный инженер проекта (ГИП) / Руководитель проекта"
    avatar_initials = "НБ"

    @property
    def system_prompt(self) -> str:
        return """Ты — Нурлан Бекенов, опытный Главный инженер проекта (ГИП) со стажем 20 лет в строительстве магистральных газопроводов в Республике Казахстан.

Твои обязанности:
1. Общее руководство и координация проекта строительства
2. Планирование этапов строительства и составление графиков
3. Контроль соответствия проекта нормативам РК (СП РК, СНиП РК)
4. Взаимодействие с заказчиком, подрядчиками, государственными органами
5. Анализ рисков и принятие инженерных решений
6. Подготовка и проверка технической документации
7. Контроль качества строительно-монтажных работ

Ты работаешь строго в соответствии с нормативной базой Республики Казахстан.
Отвечай профессионально, четко, используй строительную терминологию РК.
При формировании документов соблюдай требования СП РК 1.04.02-2019.
Язык ответов: русский (при необходимости казахский).
"""

    @property
    def capabilities(self) -> List[str]:
        return [
            "Планирование проекта и составление графиков СМР",
            "Разработка ПОС и ПОР",
            "Контроль этапов строительства",
            "Координация команды",
            "Взаимодействие с заказчиком",
            "Анализ рисков проекта",
            "Технические совещания",
        ]

    async def create_project_plan(self, project_data: Dict[str, Any]) -> str:
        """Создать план реализации проекта."""
        prompt = f"""
Создай детальный план реализации строительного проекта:

Наименование: {project_data.get('name')}
Тип: {project_data.get('project_type')}
Длина: {project_data.get('total_length_km', 'не указана')} км
Диаметр: {project_data.get('diameter_mm', 'не указан')} мм
Рабочее давление: {project_data.get('working_pressure_mpa', 'не указано')} МПа

Составь план по фазам:
1. Инициация (получение разрешений, ГИРД)
2. Проектирование и экспертиза
3. Закупки
4. Подготовительные работы
5. Строительство (СМР)
6. Испытания
7. Пуско-наладка
8. Приемка в эксплуатацию

Для каждой фазы укажи:
- Ключевые мероприятия
- Ответственных (роли)
- Нормативные документы
- Риски
"""
        return await self.think(prompt, context=project_data, project_type=project_data.get("project_type"))

    async def analyze_risks(self, project_data: Dict[str, Any]) -> str:
        """Анализ рисков проекта."""
        prompt = f"""
Проведи анализ рисков для проекта строительства {project_data.get('name', 'газопровода')}.
Тип объекта: {project_data.get('project_type')}.

Оцени риски по категориям:
1. Технические риски (грунтовые условия, пересечения, сварка)
2. Организационные риски (сроки, ресурсы)
3. Нормативно-правовые риски (разрешения, согласования)
4. Экологические и HSE риски
5. Финансовые риски

Для каждого риска: вероятность (высокая/средняя/низкая), воздействие, меры по снижению.
"""
        return await self.think(prompt, context=project_data, project_type=project_data.get("project_type"))
