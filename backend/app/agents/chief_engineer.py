"""
Серик Досмагамбетов — Главный инженер
"""
from typing import Dict, List
from app.agents.base_agent import BaseAgent


class ChiefEngineerAgent(BaseAgent):
    role = "chief_engineer"
    name_ru = "Досмагамбетов Серик Болатович"
    name_kz = "Досмағамбетов Серік Болатұлы"
    position = "Главный инженер компании"
    avatar_initials = "СД"

    @property
    def system_prompt(self) -> str:
        return """Ты — Серик Досмагамбетов, Главный инженер с 25-летним опытом в проектировании и строительстве магистральных трубопроводов в РК.

Твои обязанности:
1. Техническое руководство производством
2. Утверждение технических решений и методов производства работ
3. Контроль соответствия строительства проектной документации
4. Рассмотрение и утверждение ПОС, ПОР, ППР
5. Решение технических вопросов, возникающих в ходе строительства
6. Авторизация отступлений от проекта
7. Подготовка технических заключений

Работаешь по: СП РК 2.04-103-2013*, СНиП РК 3.01.01-2008*, ГОСТ Р ИСО 3183-2009.
Принимаешь технически обоснованные решения.
"""

    @property
    def capabilities(self) -> List[str]:
        return [
            "Технические решения по строительству",
            "Проверка ПОС, ПОР, ППР",
            "Расчеты и анализ конструктивов",
            "Утверждение методов производства работ",
            "Разбор технических проблем",
            "Анализ отступлений от проекта",
        ]

    async def review_ppr(self, ppr_data: Dict, project_data: Dict) -> str:
        prompt = f"""
Проверь и дай заключение на Проект производства работ (ППР).

Объект: {project_data.get('name')}
Тип: {project_data.get('project_type')}
Подрядчик: {project_data.get('contractor_name')}

Содержание ППР:
{ppr_data.get('description', 'Описание не предоставлено')}

Метод прокладки: {ppr_data.get('installation_method', 'открытая траншея')}
Длина участка: {ppr_data.get('length_m', 'не указана')} м

Оцени ППР по следующим критериям:
1. Соответствие требованиям СНиП РК 3.01.01-2008*
2. Полнота разделов (стройгенплан, технологические карты, охрана труда)
3. Соответствие проектным решениям
4. Достаточность мер безопасности
5. Вывод: согласовать / отправить на доработку
"""
        return await self.think(prompt, project_type=project_data.get("project_type"))

    async def resolve_technical_issue(self, issue: str, project_data: Dict) -> str:
        prompt = f"""
Реши техническую проблему, возникшую в ходе строительства:

Проект: {project_data.get('name')}
Тип: {project_data.get('project_type')}

Проблема:
{issue}

Дай:
1. Техническое заключение
2. Возможные решения
3. Рекомендуемое решение с обоснованием
4. Ссылки на НТД РК
5. Действия для оформления в документации
"""
        return await self.think(prompt, project_type=project_data.get("project_type"))
