"""
Гульнара Сейткали — Специалист охраны труда и промышленной безопасности
"""
from typing import Dict, List
from app.agents.base_agent import BaseAgent


class HSEOfficerAgent(BaseAgent):
    role = "hse_officer"
    name_ru = "Сейткали Гульнара Бекова"
    name_kz = "Сейткали Гүлнара Бекқызы"
    position = "Специалист по охране труда и промышленной безопасности (ОТ и ПБ)"
    avatar_initials = "ГС"

    @property
    def system_prompt(self) -> str:
        return """Ты — Гульнара Сейткали, специалист по охране труда и промышленной безопасности с 12-летним опытом на объектах нефтегазового строительства в Казахстане.

Твои обязанности:
1. Разработка и контроль мероприятий по охране труда на строительной площадке
2. Проведение инструктажей и обучения персонала
3. Расследование несчастных случаев и инцидентов
4. Контроль обеспечения СИЗ (средства индивидуальной защиты)
5. Разработка планов ликвидации аварийных ситуаций (ПЛАС)
6. Оформление нарядов-допусков на газоопасные и огневые работы
7. Контроль соответствия Правилам промышленной безопасности РК

Работаешь по:
- Трудовой кодекс РК от 23.11.2015 №414-V
- Правила промышленной безопасности РК (Приказы МИИР РК)
- ГОСТ 12.0.004-2015 — Обучение безопасности труда
- Правила безопасности при эксплуатации магистральных нефтегазопроводов
"""

    @property
    def capabilities(self) -> List[str]:
        return [
            "Разработка мероприятий по ОТ и ПБ",
            "Проведение инструктажей",
            "Оформление нарядов-допусков",
            "Разработка ПЛАС",
            "Расследование инцидентов",
            "Контроль СИЗ",
            "Оценка рисков ОТ",
        ]

    async def generate_safety_briefing(self, work_type: str, project_data: Dict) -> str:
        """Сформировать инструктаж по охране труда."""
        prompt = f"""
Составь целевой инструктаж по охране труда и промышленной безопасности.

Вид работ: {work_type}
Объект: {project_data.get('name')}
Рабочее давление: {project_data.get('working_pressure_mpa', 'не указано')} МПа

Инструктаж должен включать:
1. Опасные и вредные производственные факторы
2. Требования безопасности перед началом работ
3. Требования безопасности во время работ
4. Требования безопасности в аварийных ситуациях
5. Требования безопасности по окончании работ
6. Применяемые СИЗ
7. Ссылки на НТД и правила РК
"""
        return await self.think(prompt, project_type=project_data.get("project_type"))

    async def create_permit_to_work(self, work_data: Dict, project_data: Dict) -> str:
        """Оформить наряд-допуск на газоопасные/огневые работы."""
        prompt = f"""
Составь наряд-допуск на выполнение {work_data.get('work_type', 'газоопасных')} работ.

Место работы: {work_data.get('location')} (ПК {work_data.get('chainage', 'не указан')})
Характер работ: {work_data.get('description')}
Исполнители: {work_data.get('workers', 'не указаны')}
Ответственный руководитель работ: {work_data.get('responsible_person')}
Дата и время начала: {work_data.get('start_datetime')}
Дата и время окончания: {work_data.get('end_datetime')}

Объект: {project_data.get('name')}
Рабочее давление: {project_data.get('working_pressure_mpa', 'н/у')} МПа

Составь наряд-допуск по форме, установленной правилами промышленной безопасности РК.
Включи: условия безопасного выполнения работ, перечень СИЗ, меры по подготовке рабочего места.
"""
        return await self.think(prompt, project_type=project_data.get("project_type"))
