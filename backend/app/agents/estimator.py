"""
Алмас Джаксыбеков — Ведущий сметчик
"""
from typing import Dict, List
from app.agents.base_agent import BaseAgent


class EstimatorAgent(BaseAgent):
    role = "estimator"
    name_ru = "Джаксыбеков Алмас Сериккалиевич"
    name_kz = "Жақсыбеков Алмас Серікәліұлы"
    position = "Ведущий сметчик / Начальник сметного отдела"
    avatar_initials = "АД"

    @property
    def system_prompt(self) -> str:
        return """Ты — Алмас Джаксыбеков, ведущий сметчик с 15-летним опытом в строительстве трубопроводов в Казахстане.

Твои обязанности:
1. Составление смет на СМР (сметы на строительно-монтажные работы)
2. Проверка смет подрядчиков
3. Формирование КС-2 (акты выполненных работ) и КС-3 (справки о стоимости)
4. Контроль расхода материалов и ресурсов
5. Анализ сметной стоимости и отклонений

Работаешь по:
- МРР (Методические рекомендации по расчетам стоимости) РК
- Единые нормы и расценки (ЕНиР)
- РНТС РК (Ресурсно-нормативная техническая сметная документация)
- Постановления Правительства РК о сметном нормировании
"""

    @property
    def capabilities(self) -> List[str]:
        return [
            "Составление смет на СМР",
            "Проверка смет подрядчиков",
            "Формирование КС-2, КС-3",
            "Анализ стоимости работ",
            "Контроль материалов",
            "Расчет стоимости по ЕНиР",
        ]

    async def prepare_ks2(self, work_data: Dict, project_data: Dict) -> str:
        prompt = f"""
Подготовь Акт приемки выполненных работ (КС-2) для подписания.

Объект: {project_data.get('name')}
Шифр: {project_data.get('code')}
Заказчик: {project_data.get('customer_name')}
Подрядчик: {project_data.get('contractor_name')}

Выполненные работы за период:
{work_data.get('works_description', 'Строительно-монтажные работы')}
Период: {work_data.get('period', 'текущий месяц')}
Объем: {work_data.get('volume', 'не указан')}
Стоимость: {work_data.get('cost', 'не указана')} тенге

Составь КС-2 по установленной форме РК с таблицей работ и итоговыми суммами.
"""
        return await self.think(prompt, project_type=project_data.get("project_type"))
