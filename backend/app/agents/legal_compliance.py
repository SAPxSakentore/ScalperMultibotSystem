"""
Динара Касымова — Юрисконсульт / Специалист по нормативному соответствию
"""
from typing import Dict, List
from app.agents.base_agent import BaseAgent


class LegalComplianceAgent(BaseAgent):
    role = "legal_compliance"
    name_ru = "Касымова Динара Нурлановна"
    name_kz = "Қасымова Динара Нұрлановна"
    position = "Юрисконсульт / Специалист по нормативному соответствию"
    avatar_initials = "ДК"

    @property
    def system_prompt(self) -> str:
        return """Ты — Динара Касымова, юрисконсульт и специалист по нормативному соответствию в строительной отрасли РК с 12-летним опытом.

Твои обязанности:
1. Проверка разрешительной документации (ГИРД, разрешение на строительство)
2. Соответствие проекта Закону РК "Об архитектурной, градостроительной и строительной деятельности"
3. Контроль лицензий подрядчиков
4. Согласования с государственными органами (КЧС, МИИР, МЭ)
5. Договорная работа (договоры подряда, поставки)
6. Консультации по законодательству РК в строительстве
7. Подготовка к государственной приемочной комиссии

Знаешь:
- Закон РК №242-II "Об архитектурной, градостроительной и строительной деятельности"
- Закон РК "О промышленной безопасности"
- Закон РК "Об охране окружающей среды"
- Технические регламенты ЕАЭС применительно к РК
- Порядок согласования с КТЖ, МЭ РК, КЧС
"""

    @property
    def capabilities(self) -> List[str]:
        return [
            "Проверка разрешительной документации",
            "Консультации по законодательству РК",
            "Согласования с госорганами",
            "Проверка лицензий подрядчиков",
            "Договорная работа",
            "Подготовка к приемочной комиссии",
        ]

    async def check_permits(self, project_data: Dict) -> str:
        prompt = f"""
Проверь наличие и корректность разрешительной документации для строительного проекта.

Тип объекта: {project_data.get('project_type')}
Наименование: {project_data.get('name')}
Регион: {project_data.get('region')}
Заказчик: {project_data.get('customer_name')}
Разрешение на строительство: {project_data.get('permit_number', 'не получено')}

На основании Закона РК №242-II и нормативов:
1. Перечень обязательных разрешений для данного типа объекта
2. Последовательность их получения
3. Ответственные государственные органы
4. Сроки действия разрешений
5. Статус по каждому документу (✅ есть / ❌ нет / ⚠️ требует проверки)
"""
        return await self.think(prompt, project_type=project_data.get("project_type"))

    async def prepare_commissioning_package(self, project_data: Dict) -> str:
        prompt = f"""
Подготовь перечень документов для ввода объекта в эксплуатацию.

Объект: {project_data.get('name')}
Тип: {project_data.get('project_type')}
Регион: {project_data.get('region')}

Составь полный перечень документов для:
1. Государственной приемочной комиссии (КС-14)
2. Подачи в местный исполнительный орган
3. Регистрации в уполномоченных органах (МИИР РК, КЧС, КНЭ)
4. Постановки объекта на учет

Для каждого документа: кто выдает, срок получения, обязательность.
"""
        return await self.think(prompt, project_type=project_data.get("project_type"))
